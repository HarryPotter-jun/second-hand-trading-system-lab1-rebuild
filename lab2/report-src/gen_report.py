def FIG(fname, caption, max_h=330, max_w=None, folder=UML):
    path = os.path.join(folder, fname)
    pw, ph = PILImage.open(path).size
    mw = max_w or USABLE
    r = min(mw / pw, max_h / ph, 1.0)
    img = Image(path, width=pw * r, height=ph * r)
    img.hAlign = 'CENTER'
    return KeepTogether([Spacer(1, 6), img, Spacer(1, 4), Paragraph(caption, S['cap'])])

def TBL(header, rows, ratios, caption=None, center_cols=()):
    data = [[Paragraph('<b>%s</b>' % h, S['th']) for h in header]]
    for r in rows:
        data.append([Paragraph(str(c), S['tdc'] if i in center_cols else S['td'])
                     for i, c in enumerate(r)])
    widths = [x * USABLE for x in ratios]
    t = Table(data, colWidths=widths, hAlign='CENTER', repeatRows=1)
    st = [('BACKGROUND', (0, 0), (-1, 0), ACCENT),
          ('GRID', (0, 0), (-1, -1), 0.5, GRID_C),
          ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
          ('LEFTPADDING', (0, 0), (-1, -1), 6), ('RIGHTPADDING', (0, 0), (-1, -1), 6),
          ('TOPPADDING', (0, 0), (-1, -1), 4.5), ('BOTTOMPADDING', (0, 0), (-1, -1), 4.5)]
    for i in range(1, len(data)):
        st.append(('BACKGROUND', (0, i), (-1, i), colors.white if i % 2 == 1 else BG_SURFACE))
    t.setStyle(TableStyle(st))
    out = [Spacer(1, 8), t]
    if caption:
        out += [Spacer(1, 4), Paragraph(caption, S['cap'])]
    out.append(Spacer(1, 8))
    return out

