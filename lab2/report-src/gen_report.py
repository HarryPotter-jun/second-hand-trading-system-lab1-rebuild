class TocDoc(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if hasattr(flowable, 'bookmark_key'):
            self.notify('TOCEntry', (flowable.bookmark_level, flowable.bookmark_text,
                                     self.page, flowable.bookmark_key))

def _key(t):
    return 'h_' + hashlib.md5(t.encode('utf-8')).hexdigest()[:8]

def H1(text):
    k = _key(text)
    p = Paragraph('<a name="%s"/><b>%s</b>' % (k, text), S['h1'])
    p.bookmark_level, p.bookmark_text, p.bookmark_key = 0, text, k
    return [CondPageBreak(110), p,
            HRFlowable(width='100%', thickness=1.1, color=ACCENT, spaceBefore=1, spaceAfter=9)]

def H2(text):
    k = _key(text)
    p = Paragraph('<a name="%s"/><b>%s</b>' % (k, text), S['h2'])
    p.bookmark_level, p.bookmark_text, p.bookmark_key = 1, text, k
    return [CondPageBreak(70), p]

